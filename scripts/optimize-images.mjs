import { execFileSync } from "node:child_process";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const outputRoot = path.join(root, "public", "images", "optimized");
const outputUrlRoot = "/images/optimized";
const supported = /\.(?:jpe?g|png|webp|avif)$/i;
const sourceFiles = execFileSync("git", ["ls-files", "public"], { cwd: root, encoding: "utf8" })
  .split(/\r?\n/)
  .filter((file) => supported.test(file) && !file.includes("/optimized/"));
const sourceText = execFileSync("git", ["ls-files", "src"], { cwd: root, encoding: "utf8" })
  .split(/\r?\n/)
  .filter((file) => /\.(?:tsx?|css|json)$/i.test(file));
const code = await Promise.all(sourceText.map(async (file) => ({ file, text: await readFile(path.join(root, file), "utf8") })));

const bytes = (value) => `${(value / 1024).toFixed(value > 1024 * 1024 ? 0 : 1)} KiB`;
const typeFor = (relative) => {
  if (relative.includes("/hero/") || relative.includes("-hero") || relative.includes("/projects/") || relative.includes("/work/")) return "A — Critical / LCP";
  if (relative.includes("/services/") || relative.includes("/industries/") || relative.includes("/technology/")) return "C — UI / Card Images";
  return "B — Large Editorial / Project Images";
};
const sizesFor = (width, category) => {
  const candidates = category.startsWith("A") || category.startsWith("B") ? [640, 960, 1280, 1440, 1920] : [320, 480, 640, 960];
  return candidates.filter((size) => size <= width);
};
const outputName = (relative, width, format) => {
  const parsed = path.parse(relative.replace(/^public[\\/]+images[\\/]+/, ""));
  return path.join(parsed.dir, `${parsed.name}-${width}.${format}`).replaceAll("\\", "/");
};
const isUsed = (relative) => {
  const webPath = `/${relative.replace(/^public/, "").replaceAll("\\", "/")}`;
  return code.some(({ text }) => text.includes(webPath));
};
const manifest = {};
const inventory = [];
let sourceBytes = 0;
let derivativeBytes = 0;
let created = 0;

for (const relative of sourceFiles) {
  const absolute = path.join(root, relative);
  const fileStat = await stat(absolute);
  const image = sharp(absolute, { animated: false });
  const metadata = await image.metadata();
  const width = metadata.width || 0;
  const height = metadata.height || 0;
  const category = typeFor(relative);
  const source = relative.replace(/^public/, "").replaceAll("\\", "/");
  const variants = { avif: [], webp: [] };
  sourceBytes += fileStat.size;

  if (width && height) {
    const hasAlpha = Boolean(metadata.hasAlpha);
    for (const targetWidth of sizesFor(width, category)) {
      for (const format of ["avif", "webp"]) {
        const file = outputName(relative, targetWidth, format);
        const destination = path.join(outputRoot, file);
        let needsWrite = true;
        try {
          const destinationStat = await stat(destination);
          needsWrite = destinationStat.mtimeMs < fileStat.mtimeMs;
        } catch { /* create the missing derivative */ }
        if (needsWrite) {
          await mkdir(path.dirname(destination), { recursive: true });
          const transformer = sharp(absolute).resize({ width: targetWidth, withoutEnlargement: true });
          if (format === "avif") await transformer.avif({ quality: hasAlpha ? 88 : 80, effort: 5 }).toFile(destination);
          else await transformer.webp(hasAlpha ? { lossless: true } : { quality: 86, effort: 5 }).toFile(destination);
          created += 1;
        }
        const derivative = await stat(destination);
        derivativeBytes += derivative.size;
        variants[format].push({ src: `${outputUrlRoot}/${file}`, width: targetWidth, bytes: derivative.size });
      }
    }
  }

  manifest[source] = { width, height, hasAlpha: Boolean(metadata.hasAlpha), category, variants };
  inventory.push({ relative, source, width, height, fileStat, category, used: isUsed(relative), variants, hasAlpha: Boolean(metadata.hasAlpha) });
}

await mkdir(outputRoot, { recursive: true });
await writeFile(path.join(outputRoot, "image-manifest.json"), JSON.stringify(manifest, null, 2));
await mkdir(path.join(root, "src", "lib"), { recursive: true });
await writeFile(path.join(root, "src", "lib", "optimized-image-manifest.ts"), `// Generated by npm run optimize-images. Do not edit manually.\nexport type OptimizedImageRecord = { width: number; height: number; hasAlpha: boolean; category: string; variants: { avif: { src: string; width: number; bytes: number }[]; webp: { src: string; width: number; bytes: number }[] } };\nexport const optimizedImages: Record<string, OptimizedImageRecord> = ${JSON.stringify(manifest, null, 2)} as const;\n`);

const rows = inventory.map((asset) => `| \`${asset.source}\` | ${path.extname(asset.relative).slice(1).toUpperCase()} | ${asset.width} × ${asset.height} | ${bytes(asset.fileStat.size)} | ${(asset.width / asset.height).toFixed(2)} | ${asset.category} | ${asset.used ? "yes" : "not found in source"} | ${asset.category.startsWith("A") ? "possible" : "no"} | ${asset.hasAlpha ? "yes" : "no"} | ${asset.variants.avif.length ? "lazy unless the component marks it critical" : "source fallback"} |`);
const inventoryDoc = `# Image Inventory\n\nGenerated by \`npm run optimize-images\`. Only Git-tracked raster assets are processed; untracked user files are intentionally excluded. SVG assets remain vectors.\n\n- Raster assets: **${inventory.length}**\n- Source disk size: **${bytes(sourceBytes)}**\n- Generated derivatives: **${bytes(derivativeBytes)}**\n- Output location: \`public/images/optimized/\`\n\n| File | Format | Dimensions | Source size | Aspect | Class | Used in source | LCP candidate | Alpha | Loading strategy |\n|---|---|---:|---:|---:|---|---|---|---|---|\n${rows.join("\n")}\n`;
await mkdir(path.join(root, "docs", "performance"), { recursive: true });
await writeFile(path.join(root, "docs", "performance", "Image-Inventory.md"), inventoryDoc);
await writeFile(path.join(root, "docs", "performance", "Image-Optimization-Run.json"), JSON.stringify({ generatedAt: new Date().toISOString(), assets: inventory.length, sourceBytes, derivativeBytes, created, manifest }, null, 2));
console.log(`Optimized ${inventory.length} tracked raster assets; ${created} derivatives generated. Source: ${bytes(sourceBytes)}. Derivatives: ${bytes(derivativeBytes)}.`);
